# Create a NumPy array and perform arithmetic operations (addition, subtraction, multiplication, division). 
import numpy as np

a = np.array([10, 20, 30, 40])
b = np.array([2, 4, 6, 8])

print("Array A:", a)
print("Array B:", b)

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)